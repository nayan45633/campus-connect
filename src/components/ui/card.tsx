import * as React from 'react';
import { cn } from '@/lib/utils';

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  hoverable?: boolean;
}

export const Card = React.forwardRef<HTMLDivElement, CardProps>(
  ({ className, hoverable = false, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        'rounded-xl border border-slate-200/90 dark:border-dark-border bg-white dark:bg-dark-card text-slate-900 dark:text-dark-text-main shadow-sm transition-all duration-200',
        hoverable && 'hover:border-indigo-200 dark:hover:border-indigo-500/40 hover:shadow-md hover:-translate-y-0.5 cursor-pointer',
        className
      )}
      {...props}
    />
  )
);
Card.displayName = 'Card';

